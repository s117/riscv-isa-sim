#!/bin/sh
#=========================================================================
# stamp-build-info.sh <out.cc> <prefix> <title> <src-dir> <compiler> <build-type> <target>
#=========================================================================
#
# Write a C++ source that defines
#
#   extern const char *const <prefix>_build_info_fields[][3];  // {key, label, value}
#   extern const size_t <prefix>_build_info_num_fields;
#   void <prefix>_print_build_info(FILE *fp);
#
# which tell, and print, how and from what the build was made, for data provenance:
# the build host, target, compiler, date and build type, and the git
# repository, version and commit of <src-dir>. The compiler's identity and
# version are taken from its predefined macros when <out.cc> is compiled.
#
# The build systems run this on every build. <out.cc> is rewritten only if
# its content changed, so nothing else is rebuilt because of it. Outside of
# a git checkout, the git fields are "unknown".
#
# Kept identical in riscv-isa-sim and riscv-fesvr (scripts/).

set -u

if [ $# -ne 7 ]; then
  echo "usage: $0 <out.cc> <prefix> <title> <src-dir> <compiler> <build-type> <target>" >&2
  exit 1
fi

out=$1
prefix=$2
title=$3
src_dir=$4
compiler=$5
build_type=$6
target=$7

# Quote a string as the content of a C string literal
c_str() {
  printf '%s' "$1" | tr '\n' ' ' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# Run a git command in the source directory, print its output or "unknown"
git_info() {
  result=$(git -C "$src_dir" "$@" 2>/dev/null) && [ -n "$result" ] && printf '%s' "$result" || printf 'unknown'
}

hostname=$(uname -n 2>/dev/null || echo unknown)
host_system=$(uname -srm 2>/dev/null || echo unknown)
build_date=$(date '+%Y-%m-%dT%H:%M:%S%z' 2>/dev/null || echo unknown)
git_repo=$(git_info config --get remote.origin.url)
git_version=$(git_info describe --all --always --long --dirty)
git_commit=$(git_info rev-parse HEAD)
build_type=$(printf '%s' "$build_type" | tr '\n\t' '  ' | sed -e 's/  */ /g' -e 's/^ //' -e 's/ $//')
[ -n "$build_type" ] || build_type=unspecified
[ -n "$target" ] || target=unknown

tmp="$out.tmp.$$"
cat > "$tmp" <<EOF
// Generated by stamp-build-info.sh, do not edit.

#include <cstddef>
#include <cstdio>

#define STAMP_STR_(x) #x
#define STAMP_STR(x) STAMP_STR_(x)
#if defined(__clang__)
#define STAMP_CXX_COMPILER "Clang " STAMP_STR(__clang_major__) "." STAMP_STR(__clang_minor__) "." STAMP_STR(__clang_patchlevel__)
#elif defined(__GNUC__)
#define STAMP_CXX_COMPILER "GNU " __VERSION__
#elif defined(__VERSION__)
#define STAMP_CXX_COMPILER __VERSION__
#else
#define STAMP_CXX_COMPILER "unknown"
#endif

// Declared extern first: a const at namespace scope would otherwise be local to this file
extern const char *const ${prefix}_build_info_fields[][3];
extern const size_t ${prefix}_build_info_num_fields;

const char *const ${prefix}_build_info_fields[][3] = {
  {"build_hostname", "Build hostname", "$(c_str "$hostname")"},
  {"build_host", "Build host", "$(c_str "$host_system")"},
  {"build_target", "Build target", "$(c_str "$target")"},
  {"cxx_compiler", "C++ compiler", STAMP_CXX_COMPILER " ($(c_str "$compiler"))"},
  {"build_date", "Build date", "$(c_str "$build_date")"},
  {"build_type", "Build type", "$(c_str "$build_type")"},
  {"repository", "Repository", "$(c_str "$git_repo")"},
  {"version", "Version", "$(c_str "$git_version")"},
  {"commit", "Commit", "$(c_str "$git_commit")"},
};
const size_t ${prefix}_build_info_num_fields = sizeof(${prefix}_build_info_fields) / sizeof(${prefix}_build_info_fields[0]);

void ${prefix}_print_build_info(FILE *fp)
{
  fputs("$(c_str "$title") build information:\\n", fp);
  for (size_t i = 0; i < ${prefix}_build_info_num_fields; i++)
    fprintf(fp, "  %-16s- %s\\n", ${prefix}_build_info_fields[i][1], ${prefix}_build_info_fields[i][2]);
}
EOF

if cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv -f "$tmp" "$out"
fi
